import { randomUUID } from 'node:crypto'
import { expect, test } from '@playwright/test'

test('farmer reviews a lot and buyer sees the published price on mobile', async ({page, browser}) => {
  const fruit = 'กล้วยหอม-' + randomUUID().slice(0, 8)
  await page.setViewportSize({width:390, height:844})
  const session=await page.request.post('/api/ideas/idea-d/session',{data:{name:fruit,password:randomUUID(),register:true}})
  expect(session.ok()).toBe(true)
  await page.goto('/farmer')
  await page.getByRole('button', {name:'จัดการสวน',exact:true}).click()
  await expect(page.getByRole('heading',{name:'เชื่อม LINE กับสวน'})).toBeVisible()
  await page.getByRole('button',{name:'สร้างรหัสเชื่อม LINE'}).click()
  await expect(page.getByLabel('ส่งข้อความนี้ในแชตส่วนตัวกับ LINE OA ภายใน 10 นาที')).toHaveValue(/^เชื่อมสวน /)
  const farmName = 'สวนทดสอบ ' + randomUUID().slice(0, 8)
  await page.getByLabel('ชื่อสวน',{exact:true}).fill(farmName)
  await page.getByRole('button',{name:'บันทึกโปรไฟล์'}).click()
  await expect(page.getByRole('status').filter({hasText:'บันทึกโปรไฟล์แล้ว'})).toBeVisible()
  await page.getByRole('button',{name:'สร้างหรือแก้ร่าง'}).click()
  const publish = page.getByRole('button',{name:'ยืนยันลงขาย'})
  await expect(publish).toBeDisabled()
  await page.getByLabel('ชื่อผลไม้ / พันธุ์').fill(fruit)
  await page.getByLabel('ปริมาณพร้อมขาย (กก.)').fill('75')
  await page.getByLabel('ราคาขาย (บาท)').fill('36')
  await page.getByLabel('หน่วยขาย เช่น กก. หรือลัง').fill('กก.')
  await page.getByLabel('เริ่มส่งได้วันที่').fill('2026-11-30')
  await page.getByLabel('พื้นที่จัดส่ง',{exact:true}).fill('ชลบุรี')
  await page.getByRole('button',{name:'บันทึกร่างจากแบบฟอร์ม'}).click()
  await expect(publish).toBeEnabled()
  const buyer = await browser.newContext({baseURL: test.info().project.use.baseURL,viewport:{width:360,height:800},reducedMotion:'reduce'})
  try {
    const market = await buyer.newPage()
    await market.goto('/ideas/idea-d/marketplace')
    await expect(market.getByRole('heading',{name:'ตลาดผลไม้จากสวน'})).toBeVisible()
    const search = market.getByRole('searchbox')
    await search.fill(fruit)
    await expect(market.getByText('พบ 0 ล็อต')).toBeVisible()
    await publish.focus()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('heading',{name:fruit,exact:true})).toBeVisible()
    await market.reload()
    await market.getByRole('combobox',{name:'เลือกสวน'}).selectOption({label:farmName})
    const card = market.getByRole('article').filter({has:market.getByRole('heading',{name:fruit,exact:true})})
    await expect(card.getByRole('heading',{name:fruit,exact:true})).toBeVisible()
    await expect(card.getByText('฿36')).toBeVisible()
    await card.getByText('รายละเอียดล็อตและสวน').click()
    await expect(card.getByText('2026-11-30')).toBeVisible()
    await market.goto('/market?' + new URLSearchParams({q:fruit}))
    const published=market.locator('.farm-tile').filter({hasText:fruit})
    await expect(published).toContainText('36 บาท/กก.')
    await published.click()
    await expect(market.getByRole('combobox',{name:'เลือกสวน'}).locator('option:checked')).toHaveText(farmName)
    await expect(card).toBeFocused()
    for(const width of [360, 768, 1440]) {
      await market.setViewportSize({width,height:900})
      expect(await market.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    }
  } finally { await buyer.close() }
})
