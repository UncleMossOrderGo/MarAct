CREATE SCHEMA maract_farmer;
CREATE TABLE maract_farmer.farm (
    id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 2) PRIMARY KEY,
    state text NOT NULL
);
CREATE TABLE maract_farmer.owner (
    session text PRIMARY KEY, farm_id bigint NOT NULL REFERENCES maract_farmer.farm, expires bigint NOT NULL
);
CREATE TABLE maract_farmer.pairing (
    farm_id bigint PRIMARY KEY REFERENCES maract_farmer.farm, code text UNIQUE, expires bigint
);
CREATE TABLE maract_farmer.browser_pair (LIKE maract_farmer.pairing INCLUDING ALL);
CREATE TABLE maract_farmer.line_owner (
    uid text PRIMARY KEY, farm_id bigint UNIQUE NOT NULL REFERENCES maract_farmer.farm
);
CREATE TABLE maract_farmer.farmer_account (
    login text PRIMARY KEY, farm_id bigint UNIQUE NOT NULL REFERENCES maract_farmer.farm, salt bytea NOT NULL, digest bytea NOT NULL
);
CREATE TABLE maract_farmer.line_inbox (
    id text PRIMARY KEY, payload text, status text DEFAULT 'pending', lease double precision DEFAULT 0,
    attempts integer DEFAULT 0, received double precision NOT NULL, response text,
    rowid bigint GENERATED ALWAYS AS IDENTITY
);
CREATE INDEX line_work ON maract_farmer.line_inbox(status, received, rowid);
CREATE TABLE maract_farmer.photo (id text PRIMARY KEY, data bytea NOT NULL);
